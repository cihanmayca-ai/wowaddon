test("multiple labels can coexist without automatically locking", function()
    local db, char = loadDB(); M.SetTag(db, char, "guid:A", "pve", true); M.SetTag(db, char, "guid:A", "pvp", true)
    local record = M.GetRecord(char, "guid:A"); equal(#M.GetTags(db, record), 2); equal(record.locked, false)
end)
test("lock is independent of the last tag", function()
    local db, char = loadDB(); M.SetTag(db, char, "guid:A", "pve", true); M.SetLock(char, "guid:A", true)
    M.SetTag(db, char, "guid:A", "pve", false); local record = M.GetRecord(char, "guid:A")
    equal(record.locked, true); assert(M.Matches(db, { itemID = 1 }, record, "untagged", "")); assert(M.HasTag(db, record, "locked"))
end)
test("filters exclude empty slots and respect tags", function()
    local db, char = loadDB(); M.SetTag(db, char, "item:765", "gathering", true)
    local record = M.GetRecord(char, "item:765"); assert(M.Matches(db, { itemID = 765 }, record, "gathering", ""))
    assert(not M.Matches(db, { itemID = 765 }, record, "pve", "")); assert(not M.Matches(db, {}, nil, "all", ""))
end)
test("search matches names, notes, IDs and tags with Turkish folding", function()
    local db, char = loadDB(); M.SetTag(db, char, "item:765", "gathering", true); M.SetNote(char, "item:765", "İKSİR için sakla")
    local item, record = { itemID = 765, name = "Silverleaf" }, M.GetRecord(char, "item:765")
    for _, query in ipairs({ "silver", "765", "GATHERING", "iksir" }) do assert(M.Matches(db, item, record, "all", query), query) end
    assert(not M.Matches(db, item, record, "pve", "765"))
end)
test("search is literal, not a Lua pattern", function()
    local db = loadDB(); assert(M.Matches(db, { itemID = 1, name = "Ring [A]" }, nil, "all", "[A]"))
    assert(not M.Matches(db, { itemID = 1, name = "Ring ABC" }, nil, "all", "[A]"))
end)
test("custom labels create and rename, reject duplicate names", function()
    local db = loadDB(); local id = assert(M.CreateTag(db, "Fire Resist"))
    equal(M.CreateTag(db, "fire resist"), nil); equal(M.CreateTag(db, "PvE"), nil)
    assert(M.RenameTag(db, id, "Healing Set")); equal(db.tags[id].name, "Healing Set")
    assert(not M.RenameTag(db, "pve", "Whatever"))
end)
test("custom filter matches any user label", function()
    local db, char = loadDB(); local id = M.CreateTag(db, "Healing Set"); M.SetTag(db, char, "guid:A", id, true)
    assert(M.HasTag(db, M.GetRecord(char, "guid:A"), "custom"))
end)
test("deleting custom labels cleans all characters and preserves locks", function()
    local db, char = loadDB(); local id = M.CreateTag(db, "Fire Resist"); local _, other = M.Init(db, "B")
    for _, c in ipairs({ char, other }) do M.SetTag(db, c, "guid:A", id, true); M.SetLock(c, "guid:A", true) end
    assert(M.DeleteTag(db, id)); assert(not M.DeleteTag(db, "pve"))
    for _, c in ipairs({ char, other }) do local r = M.GetRecord(c, "guid:A"); equal(r.tags[id], nil); equal(r.locked, true) end
end)
test("custom label limit and markup sanitation", function()
    local db = loadDB(); local id = M.CreateTag(db, "  |cText\n  "); equal(db.tags[id].name, "cText")
    for i = 2, 32 do assert(M.CreateTag(db, "Tag " .. i)) end
    equal(M.CreateTag(db, "Overflow"), nil); equal(M.CreateTag(db, string.rep("x", 49)), nil)
end)
test("notes cannot inject WoW escape markup", function()
    local db, char = loadDB(); assert(M.SetNote(char, "A", "|cffff0000Text|r")); equal(M.GetRecord(char, "A").note, "cffff0000Textr")
    assert(not M.SetNote(char, "A", string.rep("x", 301)))
end)
