local M = GT.Model
local passed = 0
local function test(name, callback)
    local ok, message = pcall(callback)
    if not ok then error("FAIL " .. name .. ": " .. tostring(message), 0) end
    passed = passed + 1
    print("PASS " .. name)
end
local function equal(a, b) assert(a == b, "expected " .. tostring(b) .. ", got " .. tostring(a)) end
local function loadDB()
    local db, character = M.Init(nil, "A")
    return db, character
end

test("fresh database creates all agreed base tags", function()
    local db, char = loadDB(); equal(#db.order, 6); equal(db.tags.essential.name, "Essential Gear"); equal(char.settings.mode, "highlight")
end)
test("reloading keeps records, notes, colors and settings", function()
    local db, char = loadDB()
    M.SetTag(db, char, "guid:A", "pve", true); M.SetNote(char, "guid:A", "Raid için sakla")
    char.settings.mode = "only"; db.tags.pve.color = { 1, 0, 0 }
    local _, loaded = M.Init(db, "A")
    equal(M.GetRecord(loaded, "guid:A").note, "Raid için sakla"); equal(loaded.settings.mode, "only"); equal(db.tags.pve.color[1], 1)
end)
test("character records are isolated, tag definitions are shared", function()
    local db, char = loadDB(); M.SetLock(char, "item:765", true)
    local _, other = M.Init(db, "B"); equal(M.GetRecord(other, "item:765"), nil); equal(db.tags.pve.name, "PvE")
end)
test("future database is rejected without mutation", function()
